// Dataset 指向全國法規資料庫「公開資料下載」的一個 XML 壓縮檔。
type Dataset struct {
	Name    string // 本地檔名前綴
	URL     string // 官方下載網址（政府資料開放授權條款第 1 版）
	XMLName string // zip 內的 XML 檔名
}

