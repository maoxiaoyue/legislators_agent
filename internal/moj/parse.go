// rawLaw 對應 XML <法規> 元素；法規內容需保序處理（編章節與條文交錯），故自訂 Unmarshal。
type rawLaw struct {
	Nature      string     `xml:"法規性質"`
	Name        string     `xml:"法規名稱"`
	URL         string     `xml:"法規網址"`
	Category    string     `xml:"法規類別"`
	UpdatedAt   string     `xml:"最新異動日期"`
	Effective   string     `xml:"生效日期"`
	Repealed    string     `xml:"廢止註記"`
	EnglishName string     `xml:"英文法規名稱"`
	History     string     `xml:"沿革內容"`
	Preamble    string     `xml:"前言"`
	Content     rawContent `xml:"法規內容"`
}

// rawContent 以 token 走訪方式保留 <編章節> 與 <條文> 的出現順序。
type rawContent struct {
	Articles []Article
}

// UnmarshalXML 依序讀取 <法規內容> 子元素，把最近一個 <編章節> 標題附在後續條文上。
//
// @ai:generated by=claude-fable-5-1 date=2026-10-09
// @ai:purpose encoding/xml 無法直接表達「有序混合子元素」，章節歸屬需靠出現順序推得
// @ai:input d XML decoder, start 起始元素
// @ai:output error
// @ai:sideeffect 填入 c.Articles
func (c *rawContent) UnmarshalXML(d *xml.Decoder, start xml.StartElement) error {
	chapter := ""
	for {
		tok, err := d.Token()
		if err != nil {
			return err
		}
		switch t := tok.(type) {
		case xml.StartElement:
			switch t.Name.Local {
			case "編章節":
				var s string
				if err := d.DecodeElement(&s, &t); err != nil {
					return err
				}
				chapter = normalizeChapter(s)
			case "條文":
				var a struct {
					No      string `xml:"條號"`
					Content string `xml:"條文內容"`
				}
				if err := d.DecodeElement(&a, &t); err != nil {
					return err
				}
				no := normalizeArticleNo(a.No)
				c.Articles = append(c.Articles, Article{
					No:      no,
					Label:   articleLabel(no),
					Chapter: chapter,
					Content: normalizeContent(a.Content),
				})
			default:
				if err := d.Skip(); err != nil {
					return err
				}
			}
		case xml.EndElement:
			if t.Name == start.Name {
				return nil
			}
		}
	}
}

// ParseFile 以串流方式讀取 FalV.xml / MingLing.xml，只回傳符合 filter 的法規。
//
// @ai:generated by=claude-fable-5-1 date=2026-10-09
// @ai:purpose 命令資料檔逾 100MB，必須逐元素解碼而非整檔載入
// @ai:input path XML 路徑, filter 過濾條件
// @ai:output 符合條件之法規切片
// @ai:sideeffect 讀檔
func ParseFile(path string, filter Filter) ([]Law, error) {
	f, err := os.Open(path)
	if err != nil {
		return nil, fmt.Errorf("open %s: %w", path, err)
	}
	defer f.Close()
	return Parse(bufio.NewReaderSize(f, 1<<20), filter)
}

// Parse 與 ParseFile 相同，但從任意 Reader 讀取，讓測試能用小型 fixture 驗證解析邏輯。
//
// @ai:generated by=claude-fable-5-1 date=2026-10-09
// @ai:purpose 解析邏輯與檔案 I/O 分離，便於單元測試
// @ai:input r XML 內容, filter 過濾條件
// @ai:output 符合條件之法規切片
// @ai:sideeffect none
func Parse(r io.Reader, filter Filter) ([]Law, error) {
	dec := xml.NewDecoder(r)
	var out []Law
	for {
		tok, err := dec.Token()
		if err == io.EOF {
			return out, nil
		}
		if err != nil {
			return nil, fmt.Errorf("xml token: %w", err)
		}
		se, ok := tok.(xml.StartElement)
		if !ok || se.Name.Local != "法規" {
			continue
		}
		var raw rawLaw
		if err := dec.DecodeElement(&raw, &se); err != nil {
			return nil, fmt.Errorf("decode 法規: %w", err)
		}
		law := raw.toLaw()
		if filter.Match(&law) {
			out = append(out, law)
		}
	}
}

func (r rawLaw) toLaw() Law {
	return Law{
		Nature:      Nature(strings.TrimSpace(r.Nature)),
		Name:        strings.TrimSpace(r.Name),
		PCode:       pcodeFromURL(r.URL),
		SourceURL:   strings.TrimSpace(r.URL),
		Category:    strings.TrimSpace(r.Category),
		UpdatedAt:   strings.TrimSpace(r.UpdatedAt),
		Effective:   strings.TrimSpace(r.Effective),
		Repealed:    strings.TrimSpace(r.Repealed) != "",
		EnglishName: strings.TrimSpace(r.EnglishName),
		History:     strings.TrimSpace(r.History),
		Preamble:    strings.TrimSpace(r.Preamble),
		Articles:    r.Content.Articles,
	}
}

var (
	reArticleNo = regexp.MustCompile(`[第條\s]`)
	reChapter   = regexp.MustCompile(`第\s*([一二三四五六七八九十百零〇]+)\s*(編|章|節|款|目)\s*`)
	reSpaces    = regexp.MustCompile(`\s+`)
)

// normalizeArticleNo 把 "第 87-1 條" 正規化為 "87-1"；無「第…條」格式的條號原樣保留。
func normalizeArticleNo(s string) string {
	return strings.TrimSpace(reArticleNo.ReplaceAllString(s, ""))
}

func articleLabel(no string) string {
	if no == "" {
		return ""
	}
	return "第 " + no + " 條"
}

// normalizeChapter 把 "   第 一 章 總則" 正規化為 "第一章 總則"。
func normalizeChapter(s string) string {
	s = strings.TrimSpace(s)
	s = reChapter.ReplaceAllString(s, "第$1$2 ")
	return strings.TrimSpace(reSpaces.ReplaceAllString(s, " "))
}

// normalizeContent 還原資料庫固定寬度換行：縮排行為前一段之接續，頂格行為新段落。
func normalizeContent(s string) string {
	s = strings.ReplaceAll(s, "\r\n", "\n")
	var paras []string
	for _, line := range strings.Split(s, "\n") {
		if strings.TrimSpace(line) == "" {
			continue
		}
		indented := strings.HasPrefix(line, " ") || strings.HasPrefix(line, "\t") || strings.HasPrefix(line, "　")
		text := strings.Trim(line, " \t　")
		if indented && len(paras) > 0 {
			paras[len(paras)-1] += text
			continue
		}
		paras = append(paras, text)
	}
	return strings.Join(paras, "\n")
}

func pcodeFromURL(u string) string {
	const key = "pcode="
	if i := strings.LastIndex(u, key); i >= 0 {
		return strings.TrimSpace(u[i+len(key):])
	}
	return ""
}
