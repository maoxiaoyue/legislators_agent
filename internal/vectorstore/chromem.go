package vectorstore

import (
	"context"
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"

	"github.com/philippgille/chromem-go"

	"legagent/internal/embed"
)

// Chromem 以 chromem-go 持久化集合實作 Store（純 Go、零外部服務）。
type Chromem struct {
	db       *chromem.DB
	coll     *chromem.Collection
	name     string
	embedder embed.Func
	meta     map[string]string
}

// Options 為 chromem 集合的建立參數。
type Options struct {
	Path       string // 持久化目錄；空字串 = 純記憶體（測試用）
	Collection string
	Compress   bool
	// Metadata 會寫入集合層級，用於記錄 embedding provider/model 以便啟動時比對。
	Metadata map[string]string
}

// NewChromem 開啟（或建立）集合。若既有集合的 embedding 描述與本次不同，回傳錯誤以免混用向量空間。
//
// @ai:generated by=claude-fable-5-1 date=2026-10-09
// @ai:purpose 不同 embedding 模型的向量不可比，啟動期就擋下設定漂移
// @ai:input opts 參數, embedder 向量化函式
// @ai:output *Chromem, error
// @ai:sideeffect 建立 Path 目錄與集合檔
func NewChromem(opts Options, embedder embed.Func) (*Chromem, error) {
	if opts.Collection == "" {
		return nil, fmt.Errorf("vectorstore: collection name required")
	}
	var (
		db  *chromem.DB
		err error
	)
	if opts.Path == "" {
		db = chromem.NewDB()
	} else {
		db, err = chromem.NewPersistentDB(opts.Path, opts.Compress)
		if err != nil {
			return nil, fmt.Errorf("vectorstore: open %s: %w", opts.Path, err)
		}
	}

	meta := opts.Metadata
	if meta == nil {
		meta = map[string]string{}
	}
	if existing := db.GetCollection(opts.Collection, embedder); existing != nil {
		// chromem 不對外暴露集合 metadata，故以 sidecar 檔記錄建立時的 embedding 描述。
		stored, err := readMeta(opts.Path, opts.Collection)
		if err != nil {
			return nil, err
		}
		want, got := meta["embedding"], stored["embedding"]
		if want != "" && got != "" && want != got {
			return nil, fmt.Errorf("vectorstore: collection %q was built with embedding %q, config now %q (run ingest -reset)", opts.Collection, got, want)
		}
		for k, v := range stored {
			if _, ok := meta[k]; !ok {
				meta[k] = v
			}
		}
		return &Chromem{db: db, coll: existing, name: opts.Collection, embedder: embedder, meta: meta}, nil
	}

	coll, err := db.CreateCollection(opts.Collection, meta, embedder)
	if err != nil {
		return nil, fmt.Errorf("vectorstore: create collection: %w", err)
	}
	if err := writeMeta(opts.Path, opts.Collection, meta); err != nil {
		return nil, err
	}
	return &Chromem{db: db, coll: coll, name: opts.Collection, embedder: embedder, meta: meta}, nil
}

func metaPath(dir, collection string) string {
	return filepath.Join(dir, collection+".meta.json")
}

func readMeta(dir, collection string) (map[string]string, error) {
	if dir == "" {
		return map[string]string{}, nil
	}
	raw, err := os.ReadFile(metaPath(dir, collection))
	if os.IsNotExist(err) {
		return map[string]string{}, nil
	}
	if err != nil {
		return nil, fmt.Errorf("vectorstore: read meta: %w", err)
	}
	var m map[string]string
	if err := json.Unmarshal(raw, &m); err != nil {
		return nil, fmt.Errorf("vectorstore: decode meta: %w", err)
	}
	return m, nil
}

func writeMeta(dir, collection string, meta map[string]string) error {
	if dir == "" {
		return nil
	}
	raw, err := json.MarshalIndent(meta, "", "  ")
	if err != nil {
		return err
	}
	if err := os.WriteFile(metaPath(dir, collection), raw, 0o644); err != nil {
		return fmt.Errorf("vectorstore: write meta: %w", err)
	}
	return nil
}

// Upsert 先刪除同 ID 文件再寫入，因 chromem 的 Add 不覆寫既有 ID。
//
// @ai:generated by=claude-fable-5-1 date=2026-10-09
// @ai:purpose 法規每月更新，重跑 ingest 必須能覆寫舊條文
// @ai:input ctx, docs, concurrency
// @ai:output error
// @ai:sideeffect 寫入集合（持久化模式下同步落盤）
func (c *Chromem) Upsert(ctx context.Context, docs []Doc, concurrency int) error {
	if len(docs) == 0 {
		return nil
	}
	if concurrency <= 0 {
		concurrency = 1
	}
	ids := make([]string, 0, len(docs))
	cdocs := make([]chromem.Document, 0, len(docs))
	for _, d := range docs {
		ids = append(ids, d.ID)
		cdocs = append(cdocs, chromem.Document{ID: d.ID, Content: d.Content, Metadata: d.Metadata})
	}
	if c.coll.Count() > 0 {
		if err := c.coll.Delete(ctx, nil, nil, ids...); err != nil {
			return fmt.Errorf("vectorstore: delete before upsert: %w", err)
		}
	}
	if err := c.coll.AddDocuments(ctx, cdocs, concurrency); err != nil {
		return fmt.Errorf("vectorstore: add documents: %w", err)
	}
	return nil
}

// Query 回傳最相近的 k 筆；k 會被限制在文件總數內，空集合回傳空切片而非錯誤。
//
// @ai:generated by=claude-fable-5-1 date=2026-10-09
// @ai:purpose chromem 在 k > Count 時報錯，對呼叫端而言「少回幾筆」才是合理行為
// @ai:input ctx, text 查詢文字, k 筆數, where metadata 過濾
// @ai:output []Hit, error
// @ai:sideeffect 呼叫 embedding 供應者一次
func (c *Chromem) Query(ctx context.Context, text string, k int, where map[string]string) ([]Hit, error) {
	n := c.coll.Count()
	if n == 0 {
		return []Hit{}, nil
	}
	if k <= 0 {
		k = 1
	}
	if k > n {
		k = n
	}
	res, err := c.coll.Query(ctx, text, k, where, nil)
	if err != nil {
		return nil, fmt.Errorf("vectorstore: query: %w", err)
	}
	hits := make([]Hit, 0, len(res))
	for _, r := range res {
		hits = append(hits, Hit{ID: r.ID, Content: r.Content, Metadata: r.Metadata, Score: r.Similarity})
	}
	return hits, nil
}

// Count 回傳集合內文件數。
func (c *Chromem) Count() int { return c.coll.Count() }

// Describe 回傳集合 metadata。
func (c *Chromem) Describe() map[string]string { return c.meta }

// Reset 刪除並重建集合（保留原 metadata）。
//
// @ai:generated by=claude-fable-5-1 date=2026-10-09
// @ai:purpose 更換 embedding 模型或資料來源時需要乾淨重建
// @ai:input ctx
// @ai:output error
// @ai:sideeffect 刪除持久化目錄中的集合檔
func (c *Chromem) Reset(_ context.Context) error {
	if err := c.db.DeleteCollection(c.name); err != nil {
		return fmt.Errorf("vectorstore: delete collection: %w", err)
	}
	coll, err := c.db.CreateCollection(c.name, c.meta, c.embedder)
	if err != nil {
		return fmt.Errorf("vectorstore: recreate collection: %w", err)
	}
	c.coll = coll
	return nil
}
