const (
	// DefaultTopK 為未指定筆數時的回傳數。
	DefaultTopK = 5
	// MaxTopK 為單次查詢筆數上限，避免把整部法規塞進 LLM context。
	MaxTopK = 50
	// indexFile 為 data_dir 內的法規摘要清單檔名。
	indexFile = "index.json"
)

// RulesService 負責議事規則資料的建置（ingest）與語意檢索（search）。
type RulesService struct {
	store       vectorstore.Store
	dataDir     string
	log         *logger.Logger
	concurrency int
}

// NewRulesService 建立服務；concurrency 為 ingest 時同時向量化的條文數。
//
// @ai:generated by=claude-fable-5-1 date=2026-10-09
// @ai:purpose 以建構子注入 store 與 logger，讓測試可用記憶體 store + lexical embedder
// @ai:input store 向量庫, dataDir 結構化 JSON 目錄, log, concurrency
// @ai:output *RulesService
// @ai:sideeffect none
func NewRulesService(store vectorstore.Store, dataDir string, log *logger.Logger, concurrency int) *RulesService {
	if concurrency <= 0 {
		concurrency = 1
	}
	return &RulesService{store: store, dataDir: dataDir, log: log, concurrency: concurrency}
}

// IngestXML 解析一個或多個全國法規資料庫 XML，存成結構化 JSON 並寫入向量索引。
//
// @ai:generated by=claude-fable-5-1 date=2026-10-09
// @ai:purpose 單一入口把「官方 XML → data/laws JSON → 向量索引」串起來，CLI 只需呼叫一次
// @ai:input ctx, xmlPaths XML 路徑, filter 法規過濾, reset 是否先清空索引
// @ai:output *models.IngestStats, error（ErrRulesIngestFailed / ErrRulesDataUnreadable）
// @ai:sideeffect 寫入 dataDir 與向量庫
func (s *RulesService) IngestXML(ctx context.Context, xmlPaths []string, filter moj.Filter, reset bool) (*models.IngestStats, error) {
	var laws []moj.Law
	for _, p := range xmlPaths {
		got, err := moj.ParseFile(p, filter)
		if err != nil {
			s.log.Error("parse law xml failed", "path", p, "err", err)
			return nil, ErrRulesIngestFailed.With("path", p).With("reason", err.Error())
		}
		s.log.Info("parsed law xml", "path", p, "laws", len(got))
		laws = append(laws, got...)
	}
	if err := s.SaveLaws(laws); err != nil {
		return nil, err
	}
	return s.Index(ctx, laws, reset)
}

// SaveLaws 把法規寫成 data_dir/<pcode>.json 與 index.json；這份 JSON 是可入版控的資料產物。
//
// @ai:generated by=claude-fable-5-1 date=2026-10-09
// @ai:purpose 讓 CI / 其他機器不必重新下載 100MB XML 即可重建索引
// @ai:input laws
// @ai:output error（ErrRulesDataUnreadable）
// @ai:sideeffect 寫檔
func (s *RulesService) SaveLaws(laws []moj.Law) error {
	if err := os.MkdirAll(s.dataDir, 0o755); err != nil {
		s.log.Error("create data dir failed", "dir", s.dataDir, "err", err)
		return ErrRulesDataUnreadable.With("dir", s.dataDir).With("reason", err.Error())
	}
	index := make([]models.RuleLaw, 0, len(laws))
	for _, law := range laws {
		if law.PCode == "" {
			s.log.Warn("law without pcode skipped", "name", law.Name)
			continue
		}
		path := filepath.Join(s.dataDir, law.PCode+".json")
		if err := writeJSON(path, law); err != nil {
			s.log.Error("write law json failed", "path", path, "err", err)
			return ErrRulesDataUnreadable.With("path", path).With("reason", err.Error())
		}
		index = append(index, models.RuleLaw{
			Name: law.Name, PCode: law.PCode, Nature: string(law.Nature), Category: law.Category,
			UpdatedAt: law.UpdatedAt, ArticleCount: len(law.Articles), SourceURL: law.SourceURL,
		})
	}
	sort.Slice(index, func(i, j int) bool { return index[i].PCode < index[j].PCode })
	meta := map[string]any{
		"source":       "法務部全國法規資料庫公開資料（政府資料開放授權條款-第1版）",
		"generated_at": time.Now().UTC().Format(time.RFC3339),
		"laws":         index,
	}
	path := filepath.Join(s.dataDir, indexFile)
	if err := writeJSON(path, meta); err != nil {
		s.log.Error("write index failed", "path", path, "err", err)
		return ErrRulesDataUnreadable.With("path", path).With("reason", err.Error())
	}
	s.log.Info("saved laws", "dir", s.dataDir, "laws", len(index))
	return nil
}

// LoadLaws 從 data_dir 讀回所有法規 JSON。
//
// @ai:generated by=claude-fable-5-1 date=2026-10-09
// @ai:purpose 支援離線 reindex（換 embedding 模型時不必重新下載）
// @ai:input none
// @ai:output []moj.Law, error（ErrRulesDataUnreadable）
// @ai:sideeffect 讀檔
func (s *RulesService) LoadLaws() ([]moj.Law, error) {
	entries, err := os.ReadDir(s.dataDir)
	if err != nil {
		s.log.Error("read data dir failed", "dir", s.dataDir, "err", err)
		return nil, ErrRulesDataUnreadable.With("dir", s.dataDir).With("reason", err.Error())
	}
	var laws []moj.Law
	for _, e := range entries {
		name := e.Name()
		if e.IsDir() || name == indexFile || !strings.HasSuffix(name, ".json") {
			continue
		}
		path := filepath.Join(s.dataDir, name)
		raw, err := os.ReadFile(path)
		if err != nil {
			s.log.Error("read law json failed", "path", path, "err", err)
			return nil, ErrRulesDataUnreadable.With("path", path).With("reason", err.Error())
		}
		var law moj.Law
		if err := json.Unmarshal(raw, &law); err != nil {
			s.log.Error("decode law json failed", "path", path, "err", err)
			return nil, ErrRulesDataUnreadable.With("path", path).With("reason", err.Error())
		}
		laws = append(laws, law)
	}
	return laws, nil
}

// Reindex 以 data_dir 內的 JSON 重建向量索引。
//
// @ai:generated by=claude-fable-5-1 date=2026-10-09
// @ai:purpose 更換 embedding provider 後的標準重建路徑
// @ai:input ctx, reset
// @ai:output *models.IngestStats, error
// @ai:sideeffect 寫入向量庫
func (s *RulesService) Reindex(ctx context.Context, reset bool) (*models.IngestStats, error) {
	laws, err := s.LoadLaws()
	if err != nil {
		return nil, err
	}
	return s.Index(ctx, laws, reset)
}

// Index 把法規切成條文 chunk 並寫入向量庫（同 ID 覆寫）。
//
// @ai:generated by=claude-fable-5-1 date=2026-10-09
// @ai:purpose 以「一條一向量」為粒度，檢索結果可直接引用條號，便於立委問政引述
// @ai:input ctx, laws, reset
// @ai:output *models.IngestStats, error（ErrRulesIngestFailed）
// @ai:sideeffect 呼叫 embedding 供應者、寫入向量庫
func (s *RulesService) Index(ctx context.Context, laws []moj.Law, reset bool) (*models.IngestStats, error) {
	if reset {
		if err := s.store.Reset(ctx); err != nil {
			s.log.Error("reset vector store failed", "err", err)
			return nil, ErrRulesIngestFailed.With("reason", err.Error())
		}
	}
	stats := &models.IngestStats{Laws: len(laws), Embedder: s.store.Describe()["embedding"]}
	for _, law := range laws {
		chunks := BuildChunks(law)
		stats.Articles += len(law.Articles)
		docs := make([]vectorstore.Doc, 0, len(chunks))
		for _, c := range chunks {
			docs = append(docs, vectorstore.Doc{
				ID:      c.ID,
				Content: ChunkText(c),
				Metadata: map[string]string{
					"law": c.LawName, "pcode": c.PCode, "nature": c.Nature, "category": c.Category,
					"article": c.ArticleNo, "label": c.Label, "chapter": c.Chapter,
					"url": c.SourceURL, "updated_at": c.UpdatedAt,
				},
			})
		}
		if err := s.store.Upsert(ctx, docs, s.concurrency); err != nil {
			s.log.Error("upsert chunks failed", "law", law.Name, "err", err)
			return nil, ErrRulesIngestFailed.With("law", law.Name).With("reason", err.Error())
		}
		stats.Chunks += len(docs)
		s.log.Info("indexed law", "law", law.Name, "pcode", law.PCode, "chunks", len(docs))
	}
	s.log.Info("index complete", "laws", stats.Laws, "articles", stats.Articles, "chunks", stats.Chunks, "total", s.store.Count())
	return stats, nil
}

// Search 做語意檢索並回傳可引用的條文。
//
// @ai:generated by=claude-fable-5-1 date=2026-10-09
// @ai:purpose 立委 agent 回答議事程序問題時，需要附條號與來源網址的依據
// @ai:input ctx, req 查詢（Query 必填，TopK 0=5，LawName/PCode 可選）
// @ai:output *models.SearchRulesResp, error（ErrRulesInvalidRequest / ErrRulesIndexEmpty / ErrRulesSearchFailed）
// @ai:sideeffect 呼叫 embedding 供應者一次
func (s *RulesService) Search(ctx context.Context, req models.SearchRulesReq) (*models.SearchRulesResp, error) {
	req.Query = strings.TrimSpace(req.Query)
	if err := validate.Struct(req); err != nil {
		s.log.Warn("invalid search request", "err", err)
		return nil, ErrRulesInvalidRequest.With("reason", err.Error())
	}
	if s.store.Count() == 0 {
		s.log.Error("search on empty index")
		return nil, ErrRulesIndexEmpty
	}
	k := req.TopK
	if k <= 0 {
		k = DefaultTopK
	}
	if k > MaxTopK {
		k = MaxTopK
	}
	where := map[string]string{}
	if req.LawName != "" {
		where["law"] = req.LawName
	}
	if req.PCode != "" {
		where["pcode"] = req.PCode
	}
	if len(where) == 0 {
		where = nil
	}
	hits, err := s.store.Query(ctx, req.Query, k, where)
	if err != nil {
		s.log.Error("vector query failed", "query", req.Query, "err", err)
		return nil, ErrRulesSearchFailed.With("reason", err.Error())
	}
	resp := &models.SearchRulesResp{Hits: make([]models.RuleHit, 0, len(hits)), Total: len(hits)}
	for _, h := range hits {
		resp.Hits = append(resp.Hits, models.RuleHit{
			LawName:   h.Metadata["law"],
			PCode:     h.Metadata["pcode"],
			Nature:    h.Metadata["nature"],
			ArticleNo: h.Metadata["article"],
			Label:     h.Metadata["label"],
			Chapter:   h.Metadata["chapter"],
			Content:   contentOf(h.Content),
			SourceURL: h.Metadata["url"],
			Score:     h.Score,
		})
	}
	return resp, nil
}

// ListLaws 回傳 index.json 中的法規清單。
//
// @ai:generated by=claude-fable-5-1 date=2026-10-09
// @ai:purpose 讓前端 / agent 知道索引涵蓋哪些法規與資料日期
// @ai:input ctx
// @ai:output *models.ListRuleLawsResp, error（ErrRulesDataUnreadable）
// @ai:sideeffect 讀檔
func (s *RulesService) ListLaws(_ context.Context) (*models.ListRuleLawsResp, error) {
	path := filepath.Join(s.dataDir, indexFile)
	raw, err := os.ReadFile(path)
	if err != nil {
		s.log.Error("read index failed", "path", path, "err", err)
		return nil, ErrRulesDataUnreadable.With("path", path).With("reason", err.Error())
	}
	var meta struct {
		Laws []models.RuleLaw `json:"laws"`
	}
	if err := json.Unmarshal(raw, &meta); err != nil {
		s.log.Error("decode index failed", "path", path, "err", err)
		return nil, ErrRulesDataUnreadable.With("path", path).With("reason", err.Error())
	}
	return &models.ListRuleLawsResp{Laws: meta.Laws, Total: len(meta.Laws)}, nil
}

// BuildChunks 把一部法規切成每條一個 chunk。
//
// @ai:generated by=claude-fable-5-1 date=2026-10-09
// @ai:purpose 條文是法規引用的自然單位，且長度幾乎都在 embedding 模型上限內
// @ai:input law
// @ai:output []models.RuleChunk
// @ai:sideeffect none
func BuildChunks(law moj.Law) []models.RuleChunk {
	chunks := make([]models.RuleChunk, 0, len(law.Articles))
	for i, a := range law.Articles {
		no := a.No
		if no == "" {
			no = fmt.Sprintf("p%d", i+1)
		}
		chunks = append(chunks, models.RuleChunk{
			ID:        law.PCode + ":" + no,
			LawName:   law.Name,
			PCode:     law.PCode,
			Nature:    string(law.Nature),
			Category:  law.Category,
			ArticleNo: no,
			Label:     a.Label,
			Chapter:   a.Chapter,
			Content:   a.Content,
			SourceURL: law.SourceURL,
			UpdatedAt: law.UpdatedAt,
		})
	}
	return chunks
}

// chunkSeparator 分隔向量文字的標頭與條文本文，Search 時用它還原純本文。
const chunkSeparator = "\n---\n"

// ChunkText 組出送入 embedding 的文字：法規名 + 條號 + 章節 + 本文，讓向量同時帶有出處語意。
//
// @ai:generated by=claude-fable-5-1 date=2026-10-09
// @ai:purpose 「立法院議事規則 第 22 條」這類查詢需靠標頭命中，純本文無法對應條號
// @ai:input c chunk
// @ai:output 文字
// @ai:sideeffect none
func ChunkText(c models.RuleChunk) string {
	var b strings.Builder
	b.WriteString(c.LawName)
	if c.Label != "" {
		b.WriteString(" ")
		b.WriteString(c.Label)
	}
	if c.Chapter != "" {
		b.WriteString("（")
		b.WriteString(c.Chapter)
		b.WriteString("）")
	}
	b.WriteString(chunkSeparator)
	b.WriteString(c.Content)
	return b.String()
}

func contentOf(text string) string {
	if i := strings.Index(text, chunkSeparator); i >= 0 {
		return text[i+len(chunkSeparator):]
	}
	return text
}

func writeJSON(path string, v any) error {
	raw, err := json.MarshalIndent(v, "", "  ")
	if err != nil {
		return err
	}
	tmp := path + ".tmp"
	if err := os.WriteFile(tmp, raw, 0o644); err != nil {
		return err
	}
	return os.Rename(tmp, path)
}
