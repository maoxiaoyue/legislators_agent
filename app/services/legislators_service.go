// LoadLegislatorRoster 讀取並驗證名單檔，有任何不一致就拒絕，避免把錯誤資料寫進資料庫。
//
// @ai:generated by=claude-opus-5-5 date=2026-11-05
// @ai:purpose 名單檔由腳本產生，寫入前再核對一次檔內宣告的筆數與編號格式
// @ai:input path 名單 JSON 路徑
// @ai:output *models.LegislatorRoster, error（ErrLegislatorsFileUnreadable / ErrLegislatorsInvalidRoster）
// @ai:sideeffect 讀檔
func LoadLegislatorRoster(path string) (*models.LegislatorRoster, error) {
	raw, err := os.ReadFile(path)
	if err != nil {
		return nil, ErrLegislatorsFileUnreadable.With("path", path).With("reason", err.Error())
	}
	var roster models.LegislatorRoster
	if err := json.Unmarshal(raw, &roster); err != nil {
		return nil, ErrLegislatorsFileUnreadable.With("path", path).With("reason", err.Error())
	}
	invalid := func(reason string) error {
		return ErrLegislatorsInvalidRoster.With("path", path).With("reason", reason)
	}

	if len(roster.Terms) == 0 {
		return nil, invalid("no terms")
	}
	seen := map[string]bool{}
	unique := map[string]bool{}
	total := 0
	for _, set := range roster.Terms {
		if set.Term <= 0 {
			return nil, invalid(fmt.Sprintf("invalid term %d", set.Term))
		}
		if set.Count != len(set.Members) {
			return nil, invalid(fmt.Sprintf("term %d declares %d members but has %d", set.Term, set.Count, len(set.Members)))
		}
		for _, m := range set.Members {
			if !reLegislatorNo.MatchString(m.No) || m.Name == "" {
				return nil, invalid(fmt.Sprintf("term %d has invalid member %q %q", set.Term, m.No, m.Name))
			}
			key := fmt.Sprintf("%d/%s", set.Term, m.No)
			if seen[key] {
				return nil, invalid("duplicate member " + key)
			}
			seen[key] = true
			unique[m.No] = true
			total++
		}
	}
	if total != roster.TotalRecords || len(unique) != roster.UniqueLegislators {
		return nil, invalid(fmt.Sprintf("declares %d records/%d legislators but has %d/%d",
			roster.TotalRecords, roster.UniqueLegislators, total, len(unique)))
	}
	return &roster, nil
}

// BuildLegislatorRows 把名單拆成資料表列；立委姓名取其最近一屆的寫法。
//
// @ai:generated by=claude-opus-5-5 date=2026-11-05
// @ai:purpose 同一人各屆寫法可能不同（如是否附族語名），需要一個穩定規則決定主檔姓名
// @ai:input roster 已驗證的名單
// @ai:output 依編號排序的立委主檔、各屆紀錄
// @ai:sideeffect none
func BuildLegislatorRows(roster *models.LegislatorRoster) ([]models.Legislator, []models.LegislatorTerm) {
	sets := append([]models.LegislatorTermSet(nil), roster.Terms...)
	sort.Slice(sets, func(i, j int) bool { return sets[i].Term < sets[j].Term })

	latest := map[string]string{}
	var terms []models.LegislatorTerm
	for _, set := range sets {
		for _, m := range set.Members {
			latest[m.No] = m.Name
			terms = append(terms, models.LegislatorTerm{Term: set.Term, No: m.No, Name: m.Name, Note: m.Note})
		}
	}
	legislators := make([]models.Legislator, 0, len(latest))
	for no, name := range latest {
		legislators = append(legislators, models.Legislator{No: no, Name: name})
	}
	sort.Slice(legislators, func(i, j int) bool { return legislators[i].No < legislators[j].No })
	return legislators, terms
}

// Import 在單一交易內建表並寫入名單；可重複執行，筆數與名單不符時整批回滾。
//
// @ai:generated by=claude-opus-5-5 date=2026-11-05
// @ai:purpose 名單會隨來源更新重新匯入，不能留下半套或舊屆次的資料
// @ai:input ctx, roster 已驗證的名單
// @ai:output *models.LegislatorImportStats, error（ErrLegislatorsImportFailed）
// @ai:sideeffect 建立 legislators / legislator_terms 資料表並覆寫 legislator_terms 內容
func (s *LegislatorsService) Import(ctx context.Context, roster *models.LegislatorRoster) (*models.LegislatorImportStats, error) {
	legislators, terms := BuildLegislatorRows(roster)
	stats := &models.LegislatorImportStats{Terms: len(roster.Terms)}

	err := s.db.HypDBTransaction(ctx, func(ctx context.Context, tx bun.Tx) error {
		if _, err := tx.NewCreateTable().Model((*models.Legislator)(nil)).IfNotExists().Exec(ctx); err != nil {
			return fmt.Errorf("create legislators: %w", err)
		}
		if _, err := tx.NewCreateTable().Model((*models.LegislatorTerm)(nil)).IfNotExists().
			ForeignKey(`("legislator_no") REFERENCES "legislators" ("legislator_no")`).Exec(ctx); err != nil {
			return fmt.Errorf("create legislator_terms: %w", err)
		}
		if _, err := tx.NewInsert().Model(&legislators).
			On("CONFLICT (legislator_no) DO UPDATE").Set("name = EXCLUDED.name").Exec(ctx); err != nil {
			return fmt.Errorf("upsert legislators: %w", err)
		}
		if _, err := tx.NewDelete().Model((*models.LegislatorTerm)(nil)).Where("TRUE").Exec(ctx); err != nil {
			return fmt.Errorf("clear legislator_terms: %w", err)
		}
		if _, err := tx.NewInsert().Model(&terms).Exec(ctx); err != nil {
			return fmt.Errorf("insert legislator_terms: %w", err)
		}

		var err error
		if stats.Legislators, err = tx.NewSelect().Model((*models.Legislator)(nil)).Count(ctx); err != nil {
			return fmt.Errorf("count legislators: %w", err)
		}
		if stats.TermRecords, err = tx.NewSelect().Model((*models.LegislatorTerm)(nil)).Count(ctx); err != nil {
			return fmt.Errorf("count legislator_terms: %w", err)
		}
		if stats.Legislators != roster.UniqueLegislators || stats.TermRecords != roster.TotalRecords {
			return fmt.Errorf("row counts %d/%d do not match roster %d/%d",
				stats.Legislators, stats.TermRecords, roster.UniqueLegislators, roster.TotalRecords)
		}
		return nil
	})
	if err != nil {
		s.log.Error("import legislators failed", "err", err)
		return nil, ErrLegislatorsImportFailed.With("reason", err.Error())
	}
	s.log.Info("imported legislators", "legislators", stats.Legislators, "term_records", stats.TermRecords, "terms", stats.Terms)
	return stats, nil
}
