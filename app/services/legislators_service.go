// 立委名單（legislators）錯誤目錄，代碼區段 E4xxx。
var (
	// ErrLegislatorsFileUnreadable 為名單檔無法讀取或不是合法 JSON。
	ErrLegislatorsFileUnreadable = errors.Define("E4001", 500, "Legislator roster file unreadable", "legislators")
	// ErrLegislatorsInvalidRoster 為名單內容不一致，例如筆數不符或編號重複。
	ErrLegislatorsInvalidRoster = errors.Define("E4002", 422, "Legislator roster is invalid", "legislators")
	// ErrLegislatorsImportFailed 為寫入資料庫失敗；交易已回滾。
	ErrLegislatorsImportFailed = errors.Define("E4003", 500, "Legislator import failed", "legislators")
)

var reLegislatorNo = regexp.MustCompile(`^\d{4}$`)

